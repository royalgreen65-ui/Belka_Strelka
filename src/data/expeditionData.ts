// Helper to generate the remaining projected waypoints (23 to 88) across all 42 galactic regions
// so commanders can inspect the full planned 88-waypoint galactic circumnavigation trajectory
function generateProjectedWaypoints(): Waypoint[] {
  const regionsCycle = [
    { name: "Perseus Arm", ru: "Рукав Персея", angle: 1.1, r: 52000 },
    { name: "Achilles's Altar", ru: "Алтарь Ахилла", angle: 1.3, r: 48000 },
    { name: "Formidine Rift", ru: "Формидинский разлом", angle: 1.6, r: 42000 },
    { name: "Outer Arm", ru: "Внешний рукав", angle: 1.9, r: 38000 },
    { name: "Elysian Shore", ru: "Элисийский берег", angle: 2.2, r: 34000 },
    { name: "Sanguineous Rim", ru: "Кровавый обод", angle: 2.5, r: 28000 },
    { name: "Vulkan Gate", ru: "Врата Вулкана", angle: 2.9, r: 24000 },
    { name: "Inner Scutum-Centaurus", ru: "Внутренний Щит-Центавр", angle: 3.3, r: 18000 },
    { name: "Inner Orion-Perseus", ru: "Внутренний Орион-Персей", angle: 3.7, r: 12000 },
    { name: "Inner Orion Spur", ru: "Внутренний рукав Ориона", angle: 4.1, r: 4000 },
  ];

  const all: Waypoint[] = [...INITIAL_WAYPOINTS];
  const startNum = 23;
  const totalWP = 88;
  const stepDist = (EXPEDITION_STATS.estimatedDistanceLy - 55559.36) / (totalWP - 22);

  for (let i = startNum; i <= totalWP; i++) {
    const fraction = (i - 22) / (totalWP - 22);
    const regIdx = Math.floor(fraction * regionsCycle.length) % regionsCycle.length;
    const reg = regionsCycle[regIdx];
    const angle = 0.8 + fraction * 3.8;
    const radius = 35000 + Math.sin(fraction * Math.PI) * 22000;
    
    // Galactic center is around z=25900, x=0
    const x = Math.sin(angle) * radius;
    const z = 25900 + Math.cos(angle) * radius * 0.85;
    const y = Math.sin(fraction * 12) * 350;
    const distEst = 55559.36 + (i - 22) * stepDist;

    const isFinalReturn = i === totalWP;
    all.push({
      num: i,
      system: isFinalReturn ? "Meni (Arrival Hub)" : "To be announced",
      distanceNum: distEst,
      distanceStr: `${distEst.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ly`,
      reached: "0.00%",
      visited: "0.00%",
      isAnnounced: isFinalReturn,
      region: reg.name,
      regionRu: reg.ru,
      x: isFinalReturn ? -22.3 : Math.round(x),
      y: isFinalReturn ? -48.1 : Math.round(y),
      z: isFinalReturn ? 142.6 : Math.round(z),
      notableFeatures: isFinalReturn 
        ? "Expedition Grand Finale and Cartography Submission at Meni."
        : `Planned waypoint ${i} in region ${reg.name}.`,
      notableFeaturesRu: isFinalReturn
        ? "Грандиозный финал экспедиции и сдача картографических данных в Meni."
        : `Запланированная точка пути ${i} в регионе ${reg.ru}.`,
    });
  }

  return all;
}

